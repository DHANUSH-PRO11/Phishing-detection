"""
Machine Learning Training Pipeline for Phishing URL Detection.

Implements Module 2:
- Trains Logistic Regression (baseline), Random Forest, and XGBoost (optional)
- Encapsulates preprocessing inside scikit-learn Pipelines
- Fits transformers ONLY on training data (no data leakage)
- Tunes hyperparameters and operating threshold strictly on validation data
- Evaluates full suite of cybersecurity metrics (Recall, Precision, F1, PR-AUC, ROC-AUC, FPR)
- Serializes winning model, feature schema, metadata, and evaluation reports
"""

from __future__ import annotations
import sys
import json
import platform
import argparse
from datetime import datetime, timezone
from pathlib import Path
from typing import Any, Dict, List, Tuple
import joblib
import pandas as pd
import numpy as np
import scipy.optimize
import sklearn
from sklearn.base import BaseEstimator, ClassifierMixin
from sklearn.pipeline import Pipeline
from sklearn.preprocessing import StandardScaler

# Ensure project root is in sys.path
ROOT_DIR = Path(__file__).resolve().parent.parent.parent.parent
if str(ROOT_DIR) not in sys.path:
    sys.path.insert(0, str(ROOT_DIR))

from backend.app.ml.features import FEATURE_NAMES, FEATURE_METADATA
from backend.app.ml.dataset import DatasetPipeline
from backend.app.ml.evaluate import compute_metrics, find_optimal_threshold


RANDOM_SEED = 42

# Check for XGBoost availability
try:
    import xgboost as xgb
    XGBOOST_AVAILABLE = True
except ImportError:
    xgb = None
    XGBOOST_AVAILABLE = False


from backend.app.ml.estimators import LogisticRegressionBaseline, RandomForestBaseline


# Dynamic loader for sklearn models falling back to resilient baselines if DLL blocked
def get_logistic_regression() -> Any:
    try:
        from sklearn.linear_model import LogisticRegression
        return LogisticRegression(C=1.0, penalty="l2", solver="liblinear", class_weight="balanced", random_state=RANDOM_SEED, max_iter=1000)
    except (ImportError, OSError):
        return LogisticRegressionBaseline(C=1.0, max_iter=1000, random_state=RANDOM_SEED)


def get_random_forest() -> Any:
    try:
        from sklearn.ensemble import RandomForestClassifier
        return RandomForestClassifier(n_estimators=100, max_depth=8, min_samples_split=4, class_weight="balanced", random_state=RANDOM_SEED, n_jobs=-1)
    except (ImportError, OSError):
        return RandomForestBaseline(n_estimators=60, max_depth=7, min_samples_split=2, random_state=RANDOM_SEED)


def get_environment_metadata() -> Dict[str, str]:
    """Capture exact dependency and system environment versions for reproducibility."""
    meta = {
        "python_version": platform.python_version(),
        "platform": platform.platform(),
        "scikit_learn_version": sklearn.__version__,
        "pandas_version": pd.__version__,
        "numpy_version": np.__version__,
        "joblib_version": joblib.__version__,
        "xgboost_version": xgb.__version__ if XGBOOST_AVAILABLE else "Not Installed",
    }
    return meta


def load_or_generate_datasets(data_dir: Path) -> Tuple[pd.DataFrame, pd.DataFrame, pd.DataFrame]:
    """
    Loads train, validation, and test datasets generated by Module 1.
    If not yet generated, executes DatasetPipeline to prepare them.
    """
    train_path = data_dir / "train.csv"
    val_path = data_dir / "val.csv"
    test_path = data_dir / "test.csv"

    if not (train_path.exists() and val_path.exists() and test_path.exists()):
        print(f"[*] Processed datasets not found in {data_dir}. Executing DatasetPipeline...")
        pipeline = DatasetPipeline()
        pipeline.run_pipeline(output_dir=data_dir)

    train_df = pd.read_csv(train_path)
    val_df = pd.read_csv(val_path)
    test_df = pd.read_csv(test_path)

    missing_train_cols = [c for c in FEATURE_NAMES if c not in train_df.columns]
    if missing_train_cols:
        raise ValueError(f"Train dataset is missing required features: {missing_train_cols}")

    return train_df, val_df, test_df


def build_candidate_pipelines() -> Dict[str, Pipeline]:
    """
    Construct candidate model pipelines with encapsulated preprocessing.
    Preprocessing is fitted exclusively on training data during pipeline.fit().
    """
    candidates: Dict[str, Pipeline] = {}

    # 1. Logistic Regression Baseline
    candidates["LogisticRegression_Baseline"] = Pipeline([
        ("scaler", StandardScaler()),
        ("classifier", get_logistic_regression())
    ])

    # 2. Random Forest Classifier
    candidates["RandomForest_Classifier"] = Pipeline([
        ("classifier", get_random_forest())
    ])

    # 3. XGBoost Classifier (if available)
    if XGBOOST_AVAILABLE:
        candidates["XGBoost_Classifier"] = Pipeline([
            ("classifier", xgb.XGBClassifier(
                n_estimators=100,
                max_depth=5,
                learning_rate=0.08,
                subsample=0.85,
                colsample_bytree=0.85,
                scale_pos_weight=1.0,
                eval_metric="logloss",
                random_state=RANDOM_SEED,
                n_jobs=-1
            ))
        ])

    return candidates


def train_and_evaluate_all(
    train_df: pd.DataFrame,
    val_df: pd.DataFrame,
    test_df: pd.DataFrame,
    artifacts_dir: Path,
    reports_dir: Path,
) -> Dict[str, Any]:
    """
    Trains all candidate models on train data, evaluates and tunes thresholds on validation data,
    selects the superior model, and evaluates the champion once on test data.
    """
    artifacts_dir.mkdir(parents=True, exist_ok=True)
    reports_dir.mkdir(parents=True, exist_ok=True)

    X_train = train_df[FEATURE_NAMES]
    y_train = train_df["label"].to_numpy().astype(int)

    X_val = val_df[FEATURE_NAMES]
    y_val = val_df["label"].to_numpy().astype(int)

    X_test = test_df[FEATURE_NAMES]
    y_test = test_df["label"].to_numpy().astype(int)

    candidates = build_candidate_pipelines()
    candidate_results: Dict[str, Any] = {}

    best_candidate_name = ""
    best_candidate_f1 = -1.0
    best_candidate_pipeline: Pipeline | None = None
    best_candidate_threshold_info: Dict[str, Any] = {}

    for name, pipeline in candidates.items():
        print(f"[*] Training candidate model: {name} ...")
        # Preprocessing fitted ONLY on X_train
        pipeline.fit(X_train, y_train)

        # Predict probabilities on validation data
        val_proba = pipeline.predict_proba(X_val)[:, 1]

        # Validation evaluation at default 0.50 threshold
        val_metrics_default = compute_metrics(y_val, val_proba, threshold=0.50)

        # Tune threshold strictly on validation data prioritizing phishing recall
        threshold_search = find_optimal_threshold(y_val, val_proba)
        optimal_thresh = threshold_search["optimal_threshold"]
        val_metrics_optimal = threshold_search["validation_metrics_at_threshold"]

        # Train metrics for overfitting audit
        train_proba = pipeline.predict_proba(X_train)[:, 1]
        train_metrics = compute_metrics(y_train, train_proba, threshold=optimal_thresh)

        candidate_results[name] = {
            "validation_metrics_default_0.50": val_metrics_default,
            "validation_metrics_optimal_threshold": val_metrics_optimal,
            "optimal_threshold": optimal_thresh,
            "threshold_selection_rationale": threshold_search["selection_rationale"],
            "threshold_sweep_sample": threshold_search["threshold_sweep_sample"],
            "train_metrics_optimal_threshold": train_metrics,
        }

        # Model selection: Best validation F1-score with high recall
        selection_metric = val_metrics_optimal["f1_score"]
        if selection_metric > best_candidate_f1:
            best_candidate_f1 = selection_metric
            best_candidate_name = name
            best_candidate_pipeline = pipeline
            best_candidate_threshold_info = threshold_search

    assert best_candidate_pipeline is not None, "No candidate model trained successfully!"
    champion_threshold = best_candidate_threshold_info["optimal_threshold"]

    print(f"\n[+] Champion model selected: '{best_candidate_name}' (Validation F1: {best_candidate_f1:.4f}, Threshold: {champion_threshold:.2f})")

    # Evaluate champion ONCE on the unseen Test set using validation threshold
    print("[*] Evaluating champion on final unseen Test set...")
    test_proba = best_candidate_pipeline.predict_proba(X_test)[:, 1]
    final_test_metrics = compute_metrics(y_test, test_proba, threshold=champion_threshold)
    final_test_metrics_default = compute_metrics(y_test, test_proba, threshold=0.50)

    # Compile comprehensive training & evaluation report
    report_data = {
        "timestamp_utc": datetime.now(timezone.utc).isoformat(),
        "random_seed": RANDOM_SEED,
        "environment": get_environment_metadata(),
        "dataset_split_sizes": {
            "train_samples": len(train_df),
            "val_samples": len(val_df),
            "test_samples": len(test_df),
        },
        "feature_count": len(FEATURE_NAMES),
        "champion_model": {
            "name": best_candidate_name,
            "optimal_threshold": champion_threshold,
            "threshold_selection_rationale": best_candidate_threshold_info["selection_rationale"],
            "test_metrics_at_optimal_threshold": final_test_metrics,
            "test_metrics_at_default_0.50": final_test_metrics_default,
        },
        "candidates_comparison": candidate_results,
    }

    # Save serialized model artifact
    model_save_path = artifacts_dir / "model.joblib"
    joblib.dump(best_candidate_pipeline, model_save_path)
    print(f"[+] Serialized champion model saved to: {model_save_path}")

    # Save feature schema
    schema_save_path = artifacts_dir / "feature_schema.json"
    feature_schema_data = {
        "feature_names": FEATURE_NAMES,
        "feature_count": len(FEATURE_NAMES),
        "features": FEATURE_METADATA,
    }
    with open(schema_save_path, "w", encoding="utf-8") as f:
        json.dump(feature_schema_data, f, indent=2)
    print(f"[+] Feature schema saved to: {schema_save_path}")

    # Save model metadata
    metadata_save_path = artifacts_dir / "model_metadata.json"
    metadata_content = {
        "model_name": best_candidate_name,
        "algorithm": best_candidate_pipeline.named_steps["classifier"].__class__.__name__,
        "optimal_threshold": champion_threshold,
        "trained_timestamp": report_data["timestamp_utc"],
        "random_seed": RANDOM_SEED,
        "dataset_sizes": report_data["dataset_split_sizes"],
        "environment": report_data["environment"],
        "test_metrics": final_test_metrics,
        "feature_schema_file": "feature_schema.json",
        "threshold_rationale": best_candidate_threshold_info["selection_rationale"],
    }
    with open(metadata_save_path, "w", encoding="utf-8") as f:
        json.dump(metadata_content, f, indent=2)
    print(f"[+] Model metadata saved to: {metadata_save_path}")

    # Save full evaluation report
    report_save_path = reports_dir / "model_evaluation.json"
    with open(report_save_path, "w", encoding="utf-8") as f:
        json.dump(report_data, f, indent=2)
    print(f"[+] Full evaluation report saved to: {report_save_path}")

    return {
        "champion_name": best_candidate_name,
        "optimal_threshold": champion_threshold,
        "model_path": str(model_save_path),
        "metadata_path": str(metadata_save_path),
        "schema_path": str(schema_save_path),
        "report_path": str(report_save_path),
        "report_data": report_data,
    }


def main() -> int:
    parser = argparse.ArgumentParser(description="Train, evaluate, and serialize Phishing URL ML models.")
    parser.add_argument("--data-dir", type=str, default="backend/data/processed", help="Path to processed dataset CSVs.")
    parser.add_argument("--artifacts-dir", type=str, default="backend/artifacts", help="Path to save serialized model artifacts.")
    parser.add_argument("--reports-dir", type=str, default="backend/reports", help="Path to save evaluation report JSON.")
    args = parser.parse_args()

    data_dir = Path(args.data_dir)
    artifacts_dir = Path(args.artifacts_dir)
    reports_dir = Path(args.reports_dir)

    print("=" * 70)
    print(" PHISHING URL DETECTION - MODULE 2: MODEL TRAINING & EVALUATION")
    print("=" * 70)
    print(f"Data Directory:      {data_dir}")
    print(f"Artifacts Directory: {artifacts_dir}")
    print(f"Reports Directory:   {reports_dir}")

    try:
        train_df, val_df, test_df = load_or_generate_datasets(data_dir)
        results = train_and_evaluate_all(train_df, val_df, test_df, artifacts_dir, reports_dir)
    except Exception as exc:
        print(f"\n[ERROR] Training failed: {exc}", file=sys.stderr)
        return 1

    rep = results["report_data"]["champion_model"]
    test_metrics = rep["test_metrics_at_optimal_threshold"]

    print("\n" + "=" * 70)
    print(f" CHAMPION MODEL: {results['champion_name']}")
    print("=" * 70)
    print(f"Optimal Threshold:       {results['optimal_threshold']:.2f}")
    print(f"Test Accuracy:           {test_metrics['accuracy']:.2%}")
    print(f"Test Phishing Recall:    {test_metrics['recall']:.2%}")
    print(f"Test Precision:          {test_metrics['precision']:.2%}")
    print(f"Test F1-Score:           {test_metrics['f1_score']:.2%}")
    print(f"Test PR-AUC:             {test_metrics['pr_auc']:.4f}")
    print(f"Test ROC-AUC:            {test_metrics['roc_auc']:.4f}")
    print(f"Test False Positive Rate:{test_metrics['false_positive_rate']:.2%}")
    cm = test_metrics["confusion_matrix"]
    print(f"Confusion Matrix:        TN={cm['true_negatives']}, FP={cm['false_positives']}, FN={cm['false_negatives']}, TP={cm['true_positives']}")
    print("=" * 70)
    print("[SUCCESS] Module 2 model training and serialization completed.\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
